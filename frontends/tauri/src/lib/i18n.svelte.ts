const DICT: Record<Lang, Dict> = { en, ko };

/** Translate `key`, substituting `{name}` placeholders. Falls back to English, then the key. */
export function t(key: string, params?: Record<string, string | number>): string {
  const s = shortcutLabel(DICT[i18n.lang][key] ?? en[key] ?? key);
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] === undefined ? `{${k}}` : String(params[k])));
}

/** "tab 2" / "2번 탭" — the way a tab is referred to in prose. */
export const tabName = (n: number) => t("tab.n", { n });

/** Human-readable duration: 0 → none, 1500 → 1.5s, 40 → 40ms. */
export function fmtMs(ms: number): string {
  if (!ms) return t("none");
  return ms >= 1000 ? `${(ms / 1000).toFixed(ms % 1000 ? 1 : 0)}s` : `${ms}ms`;
}
