// Tiny i18n. English first; Korean second. `t()` reads `lang` from state so every
// template that calls it re-renders when the language changes.

export type Lang = "en" | "ko";
export const LANGS: { id: Lang; name: string }[] = [
  { id: "en", name: "English" },
  { id: "ko", name: "한국어" },
];

function initial(): Lang {
  try {
    const saved = localStorage.getItem("ss:lang");
    if (saved === "en" || saved === "ko") return saved;
  } catch {}
  return "en";
}

export const i18n = $state({ lang: initial() as Lang });

export function setLang(l: Lang) {
  i18n.lang = l;
  try { localStorage.setItem("ss:lang", l); } catch {}
}

